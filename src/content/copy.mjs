/** 넓이를 사람 말로 — 숫자만 적으면 감이 안 온다. */
export function walkWord(a) {
  if (a < 1) return '한 바퀴 걸어도 삼십 분이 안 걸리는 크기입니다';
  if (a < 3) return '천천히 걸어서 가로지를 만한 크기입니다';
  if (a < 10) return '걸어서 가로지르기엔 부담스러워 차를 쓰게 되는 크기입니다';
  if (a < 30) return '안에서도 차로 움직여야 하는 크기입니다';
  return '한쪽 끝에서 반대쪽까지 가는 데만도 시간이 꽤 드는 크기입니다';
}
/** 가로세로 비로 생김새를 말한다. */
export function shapeWord(ratio) {
  if (ratio >= 1.6) return '옆으로 퍼진';
  if (ratio <= 0.625) return '위아래로 긴';
  return '네모에 가까운';
}
